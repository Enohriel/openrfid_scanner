int test_stream_gcode_with_moves_and_footer() {
    // Realistic OrcaSlicer / PrusaSlicer G-code structure:
    // Header comments -> 100 G1 print move lines -> Footer summary (; filament used [mm] before [g]) -> CONFIG_BLOCK
    std::string gcode = "; generated by OrcaSlicer 2.3.0\n; thumbnail begin 32x32 100\n; AAAA\n; thumbnail end\n";
    for (int i = 0; i < 100; i++) {
        gcode += "G1 X10.0 Y10.0 E0.5 F1200\n";
    }
    gcode += "; EXECUTABLE_BLOCK_END\n";
    gcode += "; filament used [mm] = 1000.00\n";
    gcode += "; filament used [cm3] = 2.40\n";
    gcode += "; filament used [g] = 3.50\n";
    gcode += "; total filament used [g] = 3.50\n";
    gcode += "; CONFIG_BLOCK_START\n";
    gcode += "; filament_weight = 1000\n";
    gcode += "; CONFIG_BLOCK_END\n";

    // Feed in 37-byte arbitrary chunks to exercise chunk boundary line reassembly
    GcodeStreamState st;
    const uint8_t* raw = reinterpret_cast<const uint8_t*>(gcode.data());
    size_t remaining = gcode.size();
    size_t offset = 0;
    while (remaining > 0 && !st.done) {
        size_t chunk = remaining < 37 ? remaining : 37;
        feedGcodeStreamChunk(st, raw + offset, chunk);
        offset += chunk;
        remaining -= chunk;
    }
    float filament = finalizeGcodeStream(st);
    printf("(parsed %.2fg, done=%d) ", filament, st.done ? 1 : 0);
    TEST_ASSERT(fabs(filament - 3.50f) < 0.01f);
    return 0;
}

int test_stream_prusaslicer_footer_single_extruder() {
    std::string gcode;
    for (int i = 0; i < 80; i++) {
        gcode += "G1 X50.0 Y50.0 E1.2\n";
    }
    gcode += "; filament used [mm] = 3005.72\n";
    gcode += "; filament used [cm3] = 7.23\n";
    gcode += "; filament used [g] = 9.18\n";
    gcode += "; filament cost = 0.26\n";
    gcode += "; total filament used for wipe tower [g] = 0.00\n";
    gcode += "; prusaslicer_config = begin\n";
    gcode += "; filament_weight = 1000\n";

    GcodeStreamState st;
    feedGcodeStreamChunk(st, reinterpret_cast<const uint8_t*>(gcode.data()), gcode.size());
    float filament = finalizeGcodeStream(st);
    printf("(parsed %.2fg) ", filament);
    TEST_ASSERT(fabs(filament - 9.18f) < 0.01f);
    return 0;
}

